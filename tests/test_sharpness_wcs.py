"""Object width vs. stars (warm pixels), mount-position WCS (2. 11. 2026, 600 mm !Hunting/308)."""
import math
import types

import numpy as np
from astropy.io import fits

from synthtrack import search as SR
from synthtrack.astrometry import header_wcs_kind
from synthtrack.pipeline import _pointing_offset

N, H = 15, 64
DTS = np.linspace(-7.14, 7.14, N)


def _cand(x, y, vx, vy):
    return types.SimpleNamespace(x=x, y=y, vx=vx, vy=vy)


def _real(rng, fwhm, snr, motion_fwhm):
    s = fwhm / 2.3548
    a = snr / (math.sqrt(N) * s * math.sqrt(math.pi))
    v = motion_fwhm * fwhm / (DTS[-1] - DTS[0])
    yy, xx = np.mgrid[:H, :H].astype(float)
    cube = np.array([a * np.exp(-((xx - 32 - v * t) ** 2 + (yy - 32 - 0.3 * v * t) ** 2) / (2 * s * s)) for t in DTS])
    cube += rng.normal(size=cube.shape)
    return SR.sharpness(cube.astype(np.float32), DTS, _cand(32.2, 31.8, v, 0.3 * v), fwhm)


def _warm(rng, fwhm, amp, drift):
    d = np.outer(np.linspace(-0.5, 0.5, N), [0.8, 0.6]) * drift + rng.normal(0, 0.3, (N, 2))
    ky = np.fft.fftfreq(H)[:, None]
    kx = np.fft.fftfreq(H)[None, :]
    cube = rng.normal(size=(N, H, H))
    for i in range(N):
        z = np.zeros((H, H))
        z[32, 32] = amp
        cube[i] += np.real(np.fft.ifft2(np.fft.fft2(z) * np.exp(-2j * np.pi * (kx * d[i, 0] + ky * d[i, 1]))))
    A = np.stack([np.ones(N), DTS], 1)
    (x0, vx), *_ = np.linalg.lstsq(A, 32 + d[:, 0], rcond=None)
    (y0, vy), *_ = np.linalg.lstsq(A, 32 + d[:, 1], rcond=None)
    return SR.sharpness(cube.astype(np.float32), DTS, _cand(x0, y0, vx, vy), fwhm)


def _rejected(r, fwhm):
    return r is not None and r[0] < 0.65 * fwhm and r[1] >= 25.0


def test_real_objects_never_sharp_including_slow_and_undersampled():
    rng = np.random.default_rng(7)
    for fwhm in (2.0, 2.4, 3.5):
        for snr in (6, 12, 40):
            for mot in (0.5, 1.5, 4.0):
                r = _real(rng, fwhm, snr, mot)
                assert not _rejected(r, fwhm), (fwhm, snr, mot, r)


def test_warm_pixel_following_drift_is_sharp():
    rng = np.random.default_rng(3)
    hits = [_rejected(_warm(rng, 3.5, amp, 3.0), 3.5) for amp in (3.0, 4.0, 6.0, 8.0)]
    assert sum(hits) >= 3


def test_header_wcs_kind():
    h = fits.Header({"CTYPE1": "RA---TAN", "CTYPE2": "DEC--TAN", "CRVAL1": 340.3451, "CRVAL2": 12.2097,
                     "CRPIX1": 752.0, "CRPIX2": 752.0, "NAXIS1": 1504, "NAXIS2": 1504, "CDELT1": 7.18e-4,
                     "CDELT2": 7.18e-4, "CROTA2": 279.9, "RA": 340.3451, "DEC": 12.2097})
    h["COMMENT"] = "Generated by INDI"
    assert header_wcs_kind(h) == "pointing"
    h2 = h.copy()
    h2["CD1_1"] = 1e-4
    assert header_wcs_kind(h2) == "solved"
    assert header_wcs_kind(fits.Header({"NAXIS": 2})) is None


def test_pointing_offset_single_bright_object():
    k = types.SimpleNamespace(name="(198) Ampella", x=749.8, y=731.9, rate_arcsec_min=0.435, pa_deg=228.9)
    real = types.SimpleNamespace(x=743.5, y=719.1, rate_arcsec_min=0.5, pa_deg=225.0, snr=52.7,
                                 auto_status="candidate", injected=None)
    faint = types.SimpleNamespace(x=760.0, y=700.0, rate_arcsec_min=0.45, pa_deg=230.0, snr=8.0,
                                  auto_status="candidate", injected=None)
    off = _pointing_offset([real, faint], [k], 2.586, 14.28, 300.0)
    assert off is not None and abs(off[0] + 6.3) < 0.1 and abs(off[1] + 12.8) < 0.1
    # two bright detections that both fit one object: ambiguous -> no correction
    twin = types.SimpleNamespace(**{**vars(real), "x": 770.0})
    assert _pointing_offset([real, twin], [k], 2.586, 14.28, 300.0) is None
